async function loadStudents() {

  ensureSupabase();


  renderLoadingRow();


  const {
    data,
    error
  } =
    await supabaseClient
      .from("students")
      .select(
        `
          id,
          institution_id,
          auth_user_id,
          student_id,
          full_name,
          gender,
          date_of_birth,
          phone,
          email,
          address,
          photo_url,
          admission_date,
          status,
          account_enabled,
          login_username,
          account_created_at,
          last_login_at,
          password_changed_at
        `
      )
      .order(
        "created_at",
        {
          ascending: false
        }
      );


  if (error) {

    console.error(
      "Students loading error:",
      error
    );

    renderEmptyRow(
      "Unable to load students."
    );

    throw error;
  }


  students =
    data || [];


  filteredStudents =
    [...students];


  updateStatistics();

  applyFiltersAndRender();

}



