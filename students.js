/* ============================================================
   18. STATISTICS
   ============================================================ */

function updateStatistics() {

  const total =
    students.length;


  const active =
    students.filter(
      student =>
        String(
          student.status
        ).toLowerCase() === "active"
    ).length;


  const graduated =
    students.filter(
      student =>
        String(
          student.status
        ).toLowerCase() === "graduated"
    ).length;


  const other =
    total -
    active -
    graduated;


  if (totalStudentsEl) {
    totalStudentsEl.textContent =
      total;
  }

  if (activeStudentsEl) {
    activeStudentsEl.textContent =
      active;
  }

  if (graduatedStudentsEl) {
    graduatedStudentsEl.textContent =
      graduated;
  }

  if (otherStudentsEl) {
    otherStudentsEl.textContent =
      other;
  }

}



/* ============================================================
   19. FILTER
   ============================================================ */

function applyFiltersAndRender() {

  const search =
    String(
      searchInput?.value || ""
    )
      .trim()
      .toLowerCase();


  const selectedStatus =
    String(
      statusFilter?.value || ""
    )
      .trim()
      .toLowerCase();


  filteredStudents =
    students.filter(
      student => {

        const searchableText =
          [
            student.student_id,
            student.full_name,
            student.phone,
            student.email,
            student.gender,
            student.login_username
          ]
            .filter(Boolean)
            .join(" ")
            .toLowerCase();


        const matchesSearch =
          !search ||
          searchableText.includes(
            search
          );


        const matchesStatus =
          !selectedStatus ||
          String(
            student.status || ""
          ).toLowerCase() ===
          selectedStatus;


        return (
          matchesSearch &&
          matchesStatus
        );

      }
    );


  renderStudents();

}



/* ============================================================
   20. RENDER STUDENTS
   ============================================================ */

function renderStudents() {

  if (!studentsTableBody) {
    return;
  }


  if (
    !filteredStudents.length
  ) {

    renderEmptyRow(
      "No students match your search."
    );

    return;
  }


  studentsTableBody.innerHTML =
    filteredStudents
      .map(
        student =>
          createStudentRow(
            student
          )
      )
      .join("");

}



