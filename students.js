function editStudent(
  student
) {

  if (!student) {
    return;
  }


  editingStudent =
    student;


  if (editStudentDbId) {
    editStudentDbId.value =
      student.id || "";
  }


  /*
     Student ID is READ ONLY.
     We only display it.
     We NEVER update it.
  */

  if (studentIdInput) {
    studentIdInput.value =
      student.student_id || "";
  }


  if (institutionSelect) {
    institutionSelect.value =
      student.institution_id || "";
  }


  if (fullNameInput) {
    fullNameInput.value =
      student.full_name || "";
  }


  if (genderInput) {
    genderInput.value =
      student.gender || "";
  }


  if (dateOfBirthInput) {
    dateOfBirthInput.value =
      dateForInput(
        student.date_of_birth
      );
  }


  if (phoneInput) {
    phoneInput.value =
      student.phone || "";
  }


  if (emailInput) {
    emailInput.value =
      student.email || "";
  }


  if (admissionDateInput) {
    admissionDateInput.value =
      dateForInput(
        student.admission_date
      );
  }


  if (statusInput) {
    statusInput.value =
      student.status || "active";
  }


  if (addressInput) {
    addressInput.value =
      student.address || "";
  }


  currentPhotoUrl =
    student.photo_url || "";


  if (student.photo_url) {

    photoPreview.src =
      student.photo_url;

    photoPreview.style.display =
      "block";

    photoPlaceholder.style.display =
      "none";

  }
  else {

    photoPreview.src =
      "";

    photoPreview.style.display =
      "none";

    photoPlaceholder.style.display =
      "flex";

  }


  updateAccountControls(
    student
  );


  if (formTitle) {
    formTitle.textContent =
      "Edit Student";
  }


  if (saveButton) {
    saveButton.textContent =
      "Update Student";
  }


  document
    .querySelector(
      ".card"
    )
    ?.scrollIntoView({
      behavior: "smooth",
      block: "start"
    });

}



