/* ============================================================
   35. TABLE ACTION HANDLER
   ============================================================ */

async function handleTableAction(
  event
) {

  const button =
    event.target.closest(
      "button[data-action]"
    );


  if (!button) {
    return;
  }


  const action =
    button.dataset.action;


  const dbId =
    button.dataset.id;


  const student =
    findStudentByDbId(
      dbId
    );


  if (!student) {

    showMessage(
      "Student record lama helin.",
      "error"
    );

    return;
  }


  try {

    switch (
      action
    ) {

      case "view":

        viewStudent(
          student
        );

        break;


      case "edit":

        editStudent(
          student
        );

        break;


      case "create-account":

        await createStudentAccount(
          student
        );

        break;


      case "reset-password":

        await resetStudentPassword(
          student
        );

        break;


      case "delete":

        await deleteStudent(
          student
        );

        break;

    }

  }
  catch (error) {

    console.error(
      "Student action error:",
      error
    );

    showMessage(
      error?.message ||
      "Action failed.",
      "error"
    );

  }

}



