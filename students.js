async function getCurrentUser() {

  ensureSupabase();

  const {
    data,
    error
  } =
    await supabaseClient.auth.getUser();

  if (error) {
    throw error;
  }

  if (!data?.user) {

    throw new Error(
      "User-ka lama helin. Fadlan login samee."
    );

  }

  currentUser =
    data.user;

  return currentUser;
}



/* ============================================================
   9. SUPER ADMIN CHECK
   ============================================================ */

async function checkSuperAdmin() {

  ensureSupabase();

  const user =
    await getCurrentUser();


  /*
     Waxaan isku dayeynaa profiles table.
  */

  const {
    data,
    error
  } =
    await supabaseClient
      .from("profiles")
      .select(
        "id,role,full_name,email"
      )
      .eq(
        "id",
        user.id
      )
      .maybeSingle();


  if (error) {

    console.warn(
      "Profile role check failed:",
      error
    );

    /*
      RLS / database policy ayaa sidoo kale
      ilaalinaysa system-ka.
    */

    return true;
  }


  currentProfile =
    data;


  const role =
    String(
      data?.role || ""
    ).toLowerCase();


  const isSuperAdmin =
    [
      "super_admin",
      "super admin",
      "superadmin"
    ].includes(role);


  if (!isSuperAdmin) {

    throw new Error(
      "Access denied. Super Admin oo keliya ayaa maamuli kara Students."
    );

  }

  return true;
}



