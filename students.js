async function uploadStudentPhoto(
  file,
  studentDbId
) {

  ensureSupabase();


  const optimized =
    await optimizeImage(
      file
    );


  if (!optimized) {
    return null;
  }


  const extension =
    "jpg";


  const path =
    `students/${studentDbId}/${Date.now()}.${extension}`;


  showProgress(
    35,
    "Uploading student photo..."
  );


  /*
     Storage bucket:
       student-photos

     Haddii bucket-kaaga magaciisu ka duwan yahay,
     halkaan beddel.
  */

  const {
    error:
      uploadError
  } =
    await supabaseClient
      .storage
      .from(
        "student-photos"
      )
      .upload(
        path,
        optimized,
        {
          cacheControl:
            "3600",

          upsert:
            true,

          contentType:
            "image/jpeg"
        }
      );


  if (uploadError) {
    throw uploadError;
  }


  const {
    data:
      publicData
  } =
    supabaseClient
      .storage
      .from(
        "student-photos"
      )
      .getPublicUrl(
        path
      );


  return publicData?.publicUrl ||
    null;

}



/* ============================================================
   29. SAVE STUDENT
   ============================================================ */

async function saveStudent(
  event
) {

  event.preventDefault();


  if (isSaving) {
    return;
  }


  hideMessage();


  try {

    ensureSupabase();


    if (!fullNameInput.value.trim()) {

      showMessage(
        "Full Name waa required.",
        "error"
      );

      fullNameInput.focus();

      return;
    }


    if (
      !institutionSelect.value
    ) {

      showMessage(
        "Fadlan dooro Institution.",
        "error"
      );

      institutionSelect.focus();

      return;
    }


    if (
      !admissionDateInput.value
    ) {

      showMessage(
        "Admission Date waa required.",
        "error"
      );

      admissionDateInput.focus();

      return;
    }


    isSaving =
      true;

    saveButton.disabled =
      true;


    const isEdit =
      Boolean(
        editingStudent?.id
      );


    showProgress(
      10,
      isEdit
        ? "Updating student..."
        : "Saving student..."
    );


    /*
       IMPORTANT:
       student_id IS NOT included here.

       Database trigger generates:
       GA-2026-000001
       GA-2026-000002
       ...
    */


    const payload = {

      institution_id:
        institutionSelect.value,

      full_name:
        fullNameInput.value.trim(),

      gender:
        genderInput.value || null,

      date_of_birth:
        dateOfBirthInput.value || null,

      phone:
        phoneInput.value.trim() || null,

      email:
        emailInput.value.trim() || null,

      admission_date:
        admissionDateInput.value,

      status:
        statusInput.value,

      address:
        addressInput.value.trim() || null

    };


    let savedStudent = null;


    if (isEdit) {

      /*
         Student ID is NOT updated.
      */

      const {
        data,
        error
      } =
        await supabaseClient
          .from("students")
          .update(
            payload
          )
          .eq(
            "id",
            editingStudent.id
          )
          .select(
            `
              id,
              institution_id,
              auth_user_id,
              student_id,
              full_name,
              gender,
              date_of_birth,
              phone,
              email,
              address,
              photo_url,
              admission_date,
              status,
              account_enabled,
              login_username,
              account_created_at,
              last_login_at,
              password_changed_at
            `
          )
          .single();


      if (error) {
        throw error;
      }


      savedStudent =
        data;

    }
    else {

      const {
        data,
        error
      } =
        await supabaseClient
          .from("students")
          .insert(
            payload
          )
          .select(
            `
              id,
              institution_id,
              auth_user_id,
              student_id,
              full_name,
              gender,
              date_of_birth,
              phone,
              email,
              address,
              photo_url,
              admission_date,
              status,
              account_enabled,
              login_username,
              account_created_at,
              last_login_at,
              password_changed_at
            `
          )
          .single();


      if (error) {
        throw error;
      }


      savedStudent =
        data;

    }


    showProgress(
      60,
      "Student saved. Checking photo..."
    );


    /*
       PHOTO
    */

    const photoFile =
      photoInput?.files?.[0];


    if (photoFile) {

      const photoUrl =
        await uploadStudentPhoto(
          photoFile,
          savedStudent.id
        );


      if (photoUrl) {

        const {
          data,
          error
        } =
          await supabaseClient
            .from("students")
            .update({
              photo_url:
                photoUrl
            })
            .eq(
              "id",
              savedStudent.id
            )
            .select(
              `
                id,
                institution_id,
                auth_user_id,
                student_id,
                full_name,
                gender,
                date_of_birth,
                phone,
                email,
                address,
                photo_url,
                admission_date,
                status,
                account_enabled,
                login_username,
                account_created_at,
                last_login_at,
                password_changed_at
              `
            )
            .single();


        if (error) {
          throw error;
        }


        savedStudent =
          data;

      }

    }


    showProgress(
      100,
      "Completed."
    );


    /*
       Important:
       We show the newly generated Student ID.
    */

    showMessage(
      isEdit
        ? `Student ${savedStudent.student_id || ""} updated successfully.`
        : `Student created successfully. Student ID: ${savedStudent.student_id || "generated by database"}`,
      "success"
    );


    resetStudentForm();


    await loadStudents();


  }
  catch (error) {

    console.error(
      "Save student error:",
      error
    );


    let errorMessage =
      error?.message ||
      "Unable to save student.";


    /*
       Common Supabase duplicate error.
    */

    if (
      String(
        errorMessage
      ).toLowerCase()
        .includes(
          "duplicate"
        )
    ) {

      errorMessage =
        "Xogtan horey ayay u jirtaa. Fadlan hubi Student ID, Email ama xogta kale.";

    }


    showMessage(
      errorMessage,
      "error"
    );


  }
  finally {

    isSaving =
      false;

    saveButton.disabled =
      false;

    setTimeout(
      hideProgress,
      800
    );

  }

}



