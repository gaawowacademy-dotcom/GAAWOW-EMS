function money(value, currency = "USD") {
  const amount = Number(value || 0);

  return `${amount.toLocaleString("en-US", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  })} ${currency || "USD"}`;
}

function dateText(value) {
  if (!value) return "N/A";

  const date = new Date(value);

  if (Number.isNaN(date.getTime())) {
    return "N/A";
  }

  return date.toLocaleDateString();
}

function escapeHTML(value) {
  return String(value ?? "").replace(/[&<>"']/g, char => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#039;"
  })[char]);
}

function showToast(message) {
  const toast = $("toast");

  if (!toast) return;

  toast.textContent = message;
  toast.classList.add("show");

  setTimeout(() => {
    toast.classList.remove("show");
  }, 4000);
}

function showNotice(id, message, type = "info") {
  const el = $(id);

  if (!el) return;

  el.className = `notice show ${type}`;
  el.textContent = message;
}

function hideNotice(id) {
  const el = $(id);

  if (!el) return;

  el.className = "notice";
  el.textContent = "";
}

function statusBadge(status) {
  const value = String(status || "unknown").toLowerCase();

  let style = "neutral";

  if (["successful", "paid"].includes(value)) {
    style = "success";
  } else if (["pending", "overdue"].includes(value)) {
    style = "pending";
  } else if (
    ["failed", "cancelled", "refunded"].includes(value)
  ) {
    style = "failed";
  } else if (value === "partial") {
    style = "partial";
  }

  return `
    <span class="badge ${style}">
      ${escapeHTML(value)}
    </span>
  `;
}

function getStudent(studentId) {
  return students.find(s => s.id === studentId) || null;
}

function studentLabel(studentId) {
  const student = getStudent(studentId);

  if (!student) {
    return escapeHTML(studentId || "Unknown");
  }

  return `${escapeHTML(student.full_name)} (${escapeHTML(student.student_id)})`;
}

