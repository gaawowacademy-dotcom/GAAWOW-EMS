function renderPayments(filter = "") {
  const tbody = $("paymentTable");

  const filtered = payments.filter(payment => {
    const student = getStudent(payment.student_id);

    const searchText = [
      payment.payment_reference,
      payment.transaction_reference,
      payment.receipt_number,
      student?.full_name,
      student?.student_id
    ].join(" ").toLowerCase();

    return searchText.includes(
      filter.toLowerCase()
    );
  });

  if (!filtered.length) {
    tbody.innerHTML = `
      <tr>
        <td colspan="9" class="empty-state">
          No payment records found.
        </td>
      </tr>
    `;

    return;
  }

  tbody.innerHTML = filtered.map(payment => {

    const action = payment.status === "pending"
      ? `
        <button
          class="primary-btn small-btn"
          data-verify-payment="${payment.id}">
          <i class="fa-solid fa-check"></i>
          Verify
        </button>
      `
      : `
        <span class="badge neutral">
          No Action
        </span>
      `;

    return `
      <tr>

        <td>
          <strong>
            ${escapeHTML(payment.payment_reference)}
          </strong>
        </td>

        <td>
          <strong>
            ${escapeHTML(
              payment.transaction_reference || "Not generated"
            )}
          </strong>
        </td>

        <td>
          ${studentLabel(payment.student_id)}
        </td>

        <td>
          ${money(payment.amount, payment.currency)}
        </td>

        <td>
          ${escapeHTML(payment.payment_method || "N/A")}
        </td>

        <td>
          ${statusBadge(payment.status)}
        </td>

        <td>
          ${escapeHTML(payment.receipt_number || "Not issued")}
        </td>

        <td>
          ${dateText(payment.created_at)}
        </td>

        <td>
          ${action}
        </td>

      </tr>
    `;
  }).join("");

  tbody.querySelectorAll(
    "[data-verify-payment]"
  ).forEach(button => {

    button.addEventListener("click", () => {
      verifyPayment(
        button.dataset.verifyPayment,
        button
      );
    });

  });
}

