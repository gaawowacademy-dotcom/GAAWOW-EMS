// 13. VERIFY PAYMENT
// ============================================================

async function verifyPayment(paymentId, button) {

  const payment = payments.find(
    p => p.id === paymentId
  );

  if (!payment) {
    showToast("Payment record not found.");
    return;
  }

  if (payment.status !== "pending") {
    showToast(
      "Only pending payments can be verified."
    );

    return;
  }

  const confirmed = confirm(

    "IMPORTANT PAYMENT VERIFICATION\n\n" +

    "Payment Reference: " +
    payment.payment_reference + "\n" +

    "Transaction Ref: " +
    (payment.transaction_reference || "N/A") + "\n" +

    "Amount: " +
    money(payment.amount, payment.currency) + "\n\n" +

    "Only approve this payment after confirming that the money was actually received.\n\n" +

    "Continue and mark as SUCCESSFUL?"

  );

  if (!confirmed) return;

  const reviewNote = prompt(
    "Enter a verification note. Include how you confirmed receipt of the money:"
  );

  if (!reviewNote || !reviewNote.trim()) {
    showToast(
      "Verification note is required."
    );

    return;
  }

  button.disabled = true;

  button.innerHTML =
    '<i class="fa-solid fa-spinner fa-spin"></i>';

  try {

    const { data, error } = await db.rpc(
      "gaawow_finance_review_invoice_payment_v1",
      {
        p_payment_id: paymentId,
        p_decision: "successful",
        p_review_note: reviewNote.trim()
      }
    );

    if (error) throw error;

    if (!data || data.success !== true) {
      throw new Error(
        data?.message || "Payment verification failed."
      );
    }

    const receipt =
      data.receipt_number || "Receipt not returned";

    alert(

      "PAYMENT VERIFIED SUCCESSFULLY\n\n" +

      "Payment Reference: " +
      payment.payment_reference + "\n" +

      "Transaction Ref: " +
      (payment.transaction_reference || "N/A") + "\n" +

      "Receipt Number: " +
      receipt + "\n" +

      "Amount: " +
      money(payment.amount, payment.currency) + "\n\n" +

      "Invoice reconciliation is handled by the database trigger."

    );

    await loadDashboardData();

    showToast(
      "Payment successfully verified."
    );

  } catch (error) {

    console.error(
      "Payment verification error:",
      error
    );

    alert(
      "Verification failed:\n" +
      (error.message || "Unknown error")
    );

    button.disabled = false;

    button.innerHTML =
      '<i class="fa-solid fa-check"></i> Verify';

  }

}

