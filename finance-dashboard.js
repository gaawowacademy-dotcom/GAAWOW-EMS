function renderInvoices(filter = "") {
  const tbody = $("invoiceTable");

  const filtered = invoices.filter(invoice => {
    const student = getStudent(invoice.student_id);

    const searchText = [
      invoice.invoice_number,
      invoice.description,
      student?.full_name,
      student?.student_id
    ].join(" ").toLowerCase();

    return searchText.includes(
      filter.toLowerCase()
    );
  });

  if (!filtered.length) {
    tbody.innerHTML = `
      <tr>
        <td colspan="8" class="empty-state">
          No invoices found.
        </td>
      </tr>
    `;

    return;
  }

  tbody.innerHTML = filtered.map(invoice => {
    const amount = Number(invoice.amount || 0);
    const paid = Number(invoice.paid_amount || 0);

    const balance = Math.max(
      0,
      amount - paid
    );

    const canRecord =
      !["paid", "cancelled"].includes(invoice.status);

    return `
      <tr>

        <td>
          <strong>
            ${escapeHTML(invoice.invoice_number)}
          </strong>
        </td>

        <td>
          ${studentLabel(invoice.student_id)}
        </td>

        <td>
          ${money(amount, invoice.currency)}
        </td>

        <td>
          ${money(paid, invoice.currency)}
        </td>

        <td>
          <strong>
            ${money(balance, invoice.currency)}
          </strong>
        </td>

        <td>
          ${statusBadge(invoice.status)}
        </td>

        <td>
          ${dateText(invoice.due_date)}
        </td>

        <td>
          ${
            canRecord
              ? `
                <button
                  class="primary-btn small-btn"
                  data-record-invoice="${invoice.id}">
                  <i class="fa-solid fa-plus"></i>
                  Payment
                </button>
              `
              : `
                <span class="badge neutral">
                  Closed
                </span>
              `
          }
        </td>

      </tr>
    `;
  }).join("");

  tbody.querySelectorAll(
    "[data-record-invoice]"
  ).forEach(button => {

    button.addEventListener("click", () => {
      openRecordPayment(
        button.dataset.recordInvoice
      );
    });

  });
}

