// 12. SAVE PAYMENT USING SECURE RPC
// ============================================================

async function recordPayment(event) {
  event.preventDefault();

  const invoiceId =
    $("paymentInvoice").value;

  const amount =
    Number($("paymentAmount").value);

  const paymentMethod =
    $("paymentMethod").value;

  const payerPhone =
    $("payerPhone").value.trim() || null;

  // IMPORTANT:
  // Transaction Ref is generated automatically by PostgreSQL.
  // Do not create a reference in JavaScript.
  const transactionReference = null;

  if (
    !invoiceId ||
    !Number.isFinite(amount) ||
    amount <= 0 ||
    !paymentMethod
  ) {
    showNotice(
      "paymentNotice",
      "Please complete all required fields correctly.",
      "error"
    );

    return;
  }

  const invoice = invoices.find(
    item => item.id === invoiceId
  );

  if (!invoice) {
    showNotice(
      "paymentNotice",
      "Selected invoice was not found.",
      "error"
    );

    return;
  }

  const balance =
    Number(invoice.amount) -
    Number(invoice.paid_amount);

  if (amount > balance) {
    showNotice(
      "paymentNotice",
      "The amount is greater than the displayed invoice balance. Please check the amount.",
      "error"
    );

    return;
  }

  const button = $("submitPayment");

  button.disabled = true;

  button.innerHTML =
    '<i class="fa-solid fa-spinner fa-spin"></i> Processing...';

  try {

    const { data, error } = await db.rpc(
      "gaawow_finance_record_invoice_payment_v1",
      {
        p_invoice_id: invoiceId,
        p_amount: amount,
        p_payment_method: paymentMethod,
        p_payer_phone: payerPhone,
        p_transaction_reference: transactionReference
      }
    );

    if (error) throw error;

    if (!data || data.success !== true) {
      throw new Error(
        data?.message || "Payment could not be recorded."
      );
    }

    const paymentRef =
      data.payment_reference || "Not returned";

    const transactionRef =
      data.transaction_reference || "Not returned";

    showNotice(
      "paymentNotice",

      "PAYMENT RECORDED SUCCESSFULLY | " +
      "Payment Reference: " + paymentRef + " | " +
      "Transaction Ref: " + transactionRef + " | " +
      "Status: PENDING | " +
      "Receipt: Not issued yet.",

      "success"
    );

    showToast(
      "Payment recorded. Transaction Ref: " +
      transactionRef
    );

    $("recordPaymentForm").reset();

    configureAutomaticTransactionReference();

    // Reload actual database records.
    await loadDashboardData();

  } catch (error) {

    console.error(
      "Record payment error:",
      error
    );

    showNotice(
      "paymentNotice",
      error.message || "Unable to record payment.",
      "error"
    );

  } finally {

    button.disabled = false;

    button.innerHTML =
      '<i class="fa-solid fa-lock"></i> Record Payment';

  }
}

