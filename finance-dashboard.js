async function initializeDashboard() {
  try {
    const {
      data: sessionData,
      error: sessionError
    } = await db.auth.getSession();

    if (sessionError) throw sessionError;

    const session = sessionData?.session;

    if (!session) {
      window.location.replace("index.html");
      return;
    }

    currentUser = session.user;

    const {
      data: profile,
      error: profileError
    } = await db
      .from("profiles")
      .select("id, full_name, role, active, institution_id")
      .eq("id", currentUser.id)
      .maybeSingle();

    if (profileError) throw profileError;

    if (!profile) {
      throw new Error("Your user profile was not found.");
    }

    if (profile.role !== "finance_manager") {
      alert(
        "Access denied. Finance Manager account required."
      );

      await db.auth.signOut();

      window.location.replace("index.html");
      return;
    }

    if (profile.active !== true) {
      alert("Your Finance Manager account is inactive.");

      await db.auth.signOut();

      window.location.replace("index.html");
      return;
    }

    if (!profile.institution_id) {
      throw new Error(
        "Your Finance Manager account has no institution assigned."
      );
    }

    currentProfile = profile;
    institutionId = profile.institution_id;

    $("userName").textContent =
      profile.full_name || "Finance Manager";

    $("profileName").value =
      profile.full_name || "";

    $("profileInstitution").value =
      institutionId;

    configureAutomaticTransactionReference();

    await loadDashboardData();

  } catch (error) {
    console.error(
      "Dashboard initialization:",
      error
    );

    showNotice(
      "globalNotice",
      error.message || "Unable to load dashboard.",
      "error"
    );
  }
}

// ============================================================
// 6. LOAD INSTITUTION DATA
// ============================================================

async function loadDashboardData() {
  showNotice(
    "globalNotice",
    "Loading your institution's financial records...",
    "info"
  );

  const [
    studentResult,
    invoiceResult,
    paymentResult
  ] = await Promise.all([

    db.from("students")
      .select("id, institution_id, student_id, full_name")
      .eq("institution_id", institutionId),

    db.from("invoices")
      .select(
        "id, institution_id, student_id, invoice_number, description, amount, paid_amount, due_date, status, created_at, currency"
      )
      .eq("institution_id", institutionId)
      .order("created_at", { ascending: false }),

    db.from("payments")
      .select(
        "id, institution_id, invoice_id, student_id, amount, currency, payment_method, status, paid_at, created_at, payment_reference, receipt_number, transaction_reference"
      )
      .eq("institution_id", institutionId)
      .order("created_at", { ascending: false })

  ]);

  if (studentResult.error) {
    throw studentResult.error;
  }

  if (invoiceResult.error) {
    throw invoiceResult.error;
  }

  if (paymentResult.error) {
    throw paymentResult.error;
  }

  students = studentResult.data || [];
  invoices = invoiceResult.data || [];
  payments = paymentResult.data || [];

  renderDashboard();

  hideNotice("globalNotice");
}

